#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
generate_inputs.py — 生成 VASP 四大输入文件脚本

用法：
    python generate_inputs.py --task relaxation --elements "Si" --counts "2" \
        --lattice "0 0.5 0.5; 0.5 0 0.5; 0.5 0.5 0" --scale 5.43 \
        --positions "0 0 0; 0.25 0.25 0.25" --coord Direct \
        --kmesh "4 4 4" --encut 520 --outdir ./calc

这是"生成"功能的确定性脚本骨架。实际使用时，Agent 应根据用户描述的结构
和计算需求，在脚本基础上产出四个文件；本脚本提供参数化生成与模板能力，
并始终把输出写入用户指定的目录（默认当前目录）。

注意：本脚本不执行 VASP，只生成文本文件。所有输出放在 --outdir（默认当前目录）。
"""

import argparse
import os
import sys

# 可选增强库检测（同一目录下）
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _libs import HAS_ASE  # noqa: E402


def build_poscar(elements, counts, lattice, scale, positions, coord, comment="Generated by vasp-assistant"):
    """生成 POSCAR 内容。"""
    lines = []
    lines.append(comment)
    lines.append(f"{scale}")
    for vec in lattice:
        lines.append("  ".join(f"{float(x):.8f}" for x in vec))
    lines.append("  ".join(elements))
    lines.append("  ".join(str(c) for c in counts))
    lines.append(coord)
    for pos in positions:
        lines.append("  ".join(f"{float(x):.8f}" for x in pos))
    return "\n".join(lines) + "\n"


def build_kpoints(mesh, comment="Automatic mesh"):
    """生成自动网格 KPOINTS。"""
    lines = [
        comment,
        "0",
        "Monkhorst-Pack",
        "  ".join(str(m) for m in mesh),
        "0 0 0",
    ]
    return "\n".join(lines) + "\n"


def build_incar(task, encut, ismear, sigma, ediff, ediffg, ibrion, isif, nsw, system="System"):
    """生成 INCAR 内容。task: single / relax / dos / bands"""
    params = {
        "SYSTEM": system,
        "ENCUT": encut,
        "ISMEAR": ismear,
        "SIGMA": sigma,
        "EDIFF": ediff,
        "PREC": "Accurate",
    }
    if task == "relax":
        params.update({
            "EDIFFG": ediffg,
            "IBRION": ibrion,
            "ISIF": isif,
            "NSW": nsw,
        })
    elif task == "single":
        params["IBRION"] = -1
        params["NSW"] = 0
    elif task == "dos":
        params["IBRION"] = -1
        params["NSW"] = 0
        params["ISMEAR"] = -5
        params["LORBIT"] = 11
        params["ICHARG"] = 11
    elif task == "bands":
        params["IBRION"] = -1
        params["NSW"] = 0
        params["ISMEAR"] = 0
        params["LORBIT"] = 11
        params["ICHARG"] = 11

    lines = []
    for k, v in params.items():
        lines.append(f"{k} = {v}")
    return "\n".join(lines) + "\n"


def build_structure_with_ase(kind, element, a=None, size=None, vacuum=None):
    """用 ASE 构建常见结构，返回 Atoms 对象。未装 ASE 时返回 None。

    支持的 kind：
      - bulk: 常见晶体（sc/fcc/bcc/diamond/zincblende/rocksalt/hcp 等）
      - fcc111 / fcc100 / bcc111: 表面 slab
      - graphene: 石墨烯
    返回 None 表示无法构建（未装 ASE 或 kind 不支持）。
    """
    if not HAS_ASE:
        return None
    try:
        from ase.build import bulk, fcc111, fcc100, bcc111, graphene_nanoribbon
    except ImportError:
        return None

    try:
        if kind == "bulk":
            # 需指定晶格类型，默认 fcc
            # element 可传 'Si'，a 传晶格常数
            return bulk(element, crystalstructure="diamond", a=a) if element == "Si" else bulk(element, "fcc", a=a)
        elif kind == "fcc111":
            return fcc111(element, size=size or (2, 2, 3), a=a, vacuum=vacuum or 10.0)
        elif kind == "fcc100":
            return fcc100(element, size=size or (2, 2, 3), a=a, vacuum=vacuum or 10.0)
        elif kind == "bcc111":
            return bcc111(element, size=size or (2, 2, 3), a=a, vacuum=vacuum or 10.0)
        elif kind == "graphene":
            return graphene_nanoribbon(3, 1, type="zigzag")
        else:
            return None
    except Exception:
        return None


def main():
    p = argparse.ArgumentParser(description="生成 VASP 输入文件")
    p.add_argument("--task", choices=["single", "relax", "dos", "bands"], default="relax")
    p.add_argument("--elements", help="元素符号，空格分隔，如 'Si' 或 'Ga As'")
    p.add_argument("--counts", help="每种元素原子数，空格分隔，如 '2' 或 '1 1'")
    p.add_argument("--lattice", help="三条晶格矢量，分号分隔，如 '0 0.5 0.5; 0.5 0 0.5; 0.5 0.5 0'")
    p.add_argument("--scale", type=float, default=1.0, help="缩放因子")
    p.add_argument("--positions", help="原子坐标，分号分隔，每坐标3个数")
    p.add_argument("--coord", choices=["Direct", "Cartesian"], default="Direct")
    p.add_argument("--kmesh", default="4 4 4", help="k点网格，如 '4 4 4'")
    p.add_argument("--encut", type=int, default=520)
    p.add_argument("--ismear", type=int, default=0)
    p.add_argument("--sigma", type=float, default=0.05)
    p.add_argument("--ediff", type=float, default=1e-6)
    p.add_argument("--ediffg", type=float, default=-0.01)
    p.add_argument("--ibrion", type=int, default=2)
    p.add_argument("--isif", type=int, default=3)
    p.add_argument("--nsw", type=int, default=100)
    p.add_argument("--system", default="System")
    p.add_argument("--outdir", default=".", help="输出目录（默认当前目录）")
    # ASE 增强参数
    p.add_argument("--ase", action="store_true", help="用 ASE 一键构建常见结构（需装 ASE）")
    p.add_argument("--ase-kind", default="bulk", help="ASE 结构类型：bulk/fcc111/fcc100/bcc111/graphene")
    p.add_argument("--ase-a", type=float, default=None, help="ASE 晶格常数（Å）")
    p.add_argument("--ase-size", default=None, help="ASE 超胞尺寸，如 '2 2 3'")
    p.add_argument("--ase-vacuum", type=float, default=None, help="ASE 真空层厚度（Å）")
    args = p.parse_args()

    os.makedirs(args.outdir, exist_ok=True)

    # ---- ASE 增强分支：一键构建常见结构 ----
    if args.ase:
        if not HAS_ASE:
            print("[降级] 未安装 ASE，无法使用 --ase 一键建结构。")
            print("       请改用 --lattice/--positions 手写结构，或先 pip install ase。")
            sys.exit(2)
        size = tuple(int(x) for x in args.ase_size.split()) if args.ase_size else None
        atoms = build_structure_with_ase(
            args.ase_kind, args.elements, a=args.ase_a, size=size, vacuum=args.ase_vacuum
        )
        if atoms is None:
            print(f"[错误] ASE 无法构建 kind='{args.ase_kind}' 的结构，或参数不足。")
            sys.exit(1)
        # 用 ASE 写出标准 POSCAR
        poscar_path = os.path.join(args.outdir, "POSCAR")
        from ase.io import write
        write(poscar_path, atoms, format="vasp", vasp5=True, direct=True)
        # 提取元素与原子数，供 KPOINTS/INCAR 使用
        symbols = atoms.get_chemical_symbols()
        elements_order = []
        for s in symbols:
            if s not in elements_order:
                elements_order.append(s)
        counts = [symbols.count(s) for s in elements_order]
        print(f"[OK] ASE 已构建 {args.ase_kind} 结构，写出 POSCAR（{len(symbols)} 原子）")
        print(f"     元素: {elements_order}, 原子数: {counts}")
    else:
        # ---- 零依赖分支：手写结构 ----
        elements = args.elements.split()
        counts = [int(c) for c in args.counts.split()]
        lattice = [[float(x) for x in vec.split()] for vec in args.lattice.split(";")]
        positions = [[float(x) for x in pos.split()] for pos in args.positions.split(";")]
        poscar = build_poscar(elements, counts, lattice, args.scale, positions, args.coord)
        with open(os.path.join(args.outdir, "POSCAR"), "w") as f:
            f.write(poscar)
        elements_order = elements
        print(f"[OK] 已生成 POSCAR（手写结构，{sum(counts)} 原子）")

    # KPOINTS
    kmesh = [int(m) for m in args.kmesh.split()]
    kpoints = build_kpoints(kmesh)

    # INCAR
    incar = build_incar(args.task, args.encut, args.ismear, args.sigma,
                        args.ediff, args.ediffg, args.ibrion, args.isif,
                        args.nsw, args.system)

    # 写入 KPOINTS / INCAR
    with open(os.path.join(args.outdir, "KPOINTS"), "w") as f:
        f.write(kpoints)
    with open(os.path.join(args.outdir, "INCAR"), "w") as f:
        f.write(incar)

    # POTCAR 无法自动生成（需真实赝势库），提示用户
    print(f"[OK] 已生成 KPOINTS / INCAR 到 {os.path.abspath(args.outdir)}")
    print("[提示] POTCAR 需从赝势库按元素顺序拼接（POSCAR 顺序）：")
    print(f"       cat <path>/{'/POTCAR '.join(elements_order)}/POTCAR > POTCAR" if elements_order else "       (请提供 --elements)")


if __name__ == "__main__":
    main()
